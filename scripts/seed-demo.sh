#!/usr/bin/env bash
# Creates a demo hotel on LOCAL Supabase for clicking through the app (http://localhost:8081, npm run dev -- --mode localdb --port 8081).
# Demo sign-ins get generated passwords, written only to .env.localdb.local (git-ignored). Refuses non-local databases.
# Usage: scripts/seed-demo.sh     (run after scripts/test-db.sh, which wipes the local database)
set -euo pipefail
cd "$(dirname "$0")/.."
export SUPABASE_PROJECT_ID=hotel-desk
eval "$(supabase status -o env 2>/dev/null | grep -E '^(API_URL|PUBLISHABLE_KEY|SERVICE_ROLE_KEY|DB_URL)=')"
case "$API_URL" in http://127.0.0.1:*|http://localhost:*) ;; *) echo "Refusing: not a local Supabase ($API_URL)"; exit 2;; esac

env_file=.env.localdb.local
{
  echo "# LOCAL Supabase only (Docker). Used by: npm run dev -- --mode localdb --port 8081"
  echo "# Demo sign-ins generated by scripts/seed-demo.sh. Git-ignored. Local test values only."
  echo "VITE_SUPABASE_URL=$API_URL"
  echo "VITE_SUPABASE_PUBLISHABLE_KEY=$PUBLISHABLE_KEY"
  echo "VITE_SUPABASE_PROJECT_ID=local"
} > "$env_file"

ids=""
for role in admin fdo rsv fom hks att mnt acc csh; do
  email="demo-$role@hotel.test"
  pw="Demo-$(openssl rand -hex 6)"
  id=$(curl -s -X POST "$API_URL/auth/v1/admin/users" -H "apikey: $SERVICE_ROLE_KEY" -H "Authorization: Bearer $SERVICE_ROLE_KEY" \
    -H "Content-Type: application/json" -d "{\"email\":\"$email\",\"password\":\"$pw\",\"email_confirm\":true}" \
    | python3 -c "import sys,json; print(json.load(sys.stdin).get('id',''))")
  [ -n "$id" ] || { echo "Could not create $email (already seeded? run scripts/test-db.sh first)"; exit 2; }
  up=$(echo "$role" | tr a-z A-Z)
  echo "DEMO_${up}_EMAIL=$email" >> "$env_file"
  echo "DEMO_${up}_PASSWORD=$pw" >> "$env_file"
  ids+="('$role','$id'),"
done
ids=${ids%,}

psql "$DB_URL" -X -q -v ON_ERROR_STOP=1 <<SQL >/dev/null
create temp table demo_ids(role text primary key, id uuid);
insert into demo_ids values $ids;
create function pg_temp.act(r text) returns void language plpgsql as \$\$
begin
  execute 'reset role';
  perform set_config('request.jwt.claims', json_build_object('sub', (select id from demo_ids where role = r), 'role', 'authenticated')::text, false);
  perform set_config('app.settlement', '', false);
  execute 'set role authenticated';
end \$\$;
grant select on demo_ids to authenticated;
grant execute on all functions in schema pg_temp to authenticated;
do \$\$
declare h record; p uuid; bd date; std uuid; dlx uuid; ste uuid; bar uuid; corp uuid; g uuid[] := '{}'; r uuid; v uuid; n int;
  v_staff text[][] := array[['fdo','FDO'],['rsv','RES'],['fom','FOM'],['hks','HKS'],['att','RA'],['mnt','MNT'],['acc','ACCT'],['csh','CASHIER']];
begin
  perform pg_temp.act('admin');
  select * into h from public.create_hotel('Lagoon View Hotels Ltd', 'NG', 'Lagoon View Ikoyi', 'Adaeze Admin', 'Lagos');
  p := h.property_id;
  foreach n in array array[1,2,3,4,5,6,7,8] loop
    perform public.register_invited_user((select id from demo_ids where role = v_staff[n][1]), initcap(v_staff[n][1]) || ' Demo', null);
    perform public.assign_role((select id from demo_ids where role = v_staff[n][1]), p, (select id from public.roles where tenant_id is null and code = v_staff[n][2]));
  end loop;
  select business_date into bd from public.properties where id = p;
  std := public.save_room_type(p, null, 'STD', 'Standard', 2, 1, 'Queen bed', true);
  dlx := public.save_room_type(p, null, 'DLX', 'Deluxe', 2, 2, 'King bed, lagoon view', true);
  ste := public.save_room_type(p, null, 'STE', 'Suite', 3, 2, 'Living room', true);
  perform public.bulk_add_rooms(p, 101, 108, std, '1');
  perform public.bulk_add_rooms(p, 201, 206, dlx, '2');
  perform public.bulk_add_rooms(p, 301, 302, ste, '3');
  bar := public.save_rate_plan(p, null, 'BAR', 'Best available rate', false, 'nights', 1, 'nights', 1, 'none', 0, true, 2);
  corp := public.save_rate_plan(p, null, 'CORP', 'Corporate', true, 'none', 0, 'nights', 1, 'percent', 50, true, 1);
  perform public.save_rate_plan_price(null, bar, std, bd - 30, bd + 365, 55000, 'NGN');
  perform public.save_rate_plan_price(null, bar, dlx, bd - 30, bd + 365, 85000, 'NGN');
  perform public.save_rate_plan_price(null, bar, ste, bd - 30, bd + 365, 150000, 'NGN');
  perform public.save_rate_plan_price(null, corp, std, bd - 30, bd + 365, 48000, 'NGN');
  perform public.save_rate_plan_price(null, corp, dlx, bd - 30, bd + 365, 75000, 'NGN');
  perform public.set_exchange_rate(p, 'USD', bd, 1550);

  perform pg_temp.act('fdo');
  g := g || public.save_guest(null, 'Chinedu', 'Okafor', '08031234501', 'chinedu@example.ng', 'NG', 'Lekki', null);
  g := g || public.save_guest(null, 'Amina', 'Bello', '08031234502', 'amina@example.ng', 'NG', null, null);
  g := g || public.save_guest(null, 'Tunde', 'Balogun', '08031234503', null, 'NG', null, null);
  g := g || public.save_guest(null, 'Grace', 'Mensah', '0244123456', 'grace@example.gh', 'GH', null, null);
  g := g || public.save_guest(null, 'John', 'Smith', '+447700900123', 'john@example.co.uk', 'GB', null, null);
  g := g || public.save_guest(null, 'Ngozi', 'Eze', '08031234506', null, 'NG', null, null);

  -- Two guests in house with charges, one arriving today, one tomorrow, one next week (corporate)
  r := public.create_reservation(p, 'demo-1', g[1], bd, bd + 3, dlx, bar, 2, 0, 'confirmed', 'direct', null, 'Late check-out if possible', null, 'none', null, null, null, null);
  perform public.check_in(r, '{"id_type":"passport","id_number":"A0000001","nationality":"NG"}'::jsonb, (select id from public.rooms where property_id = p and room_number = '201'), null, null);
  perform public.post_charge(public.open_main_folio(r), (select id from public.charge_codes where property_id = p and code = 'REST'), 18500, false, 'Dinner for two', null, 'demo-c1');
  perform public.post_charge(public.open_main_folio(r), (select id from public.charge_codes where property_id = p and code = 'MINIBAR'), 4200, false, 'Minibar', null, 'demo-c2');
  r := public.create_reservation(p, 'demo-2', g[2], bd, bd + 1, std, bar, 1, 0, 'confirmed', 'phone', null, null, null, 'none', null, null, null, null);
  perform public.check_in(r, '{"id_type":"national_id","id_number":"NIN12345","nationality":"NG"}'::jsonb, (select id from public.rooms where property_id = p and room_number = '101'), null, null);
  perform public.post_charge(public.open_main_folio(r), (select id from public.charge_codes where property_id = p and code = 'LAUNDRY'), 6000, false, 'Laundry', null, 'demo-c3');
  perform public.post_payment(public.open_main_folio(r), (select id from public.payment_methods where property_id = p and code = 'POS'), 3000, 'NGN', false, null, 'POS 7781', 'demo-p1');
  perform public.create_reservation(p, 'demo-3', g[3], bd, bd + 2, std, bar, 1, 0, 'confirmed', 'direct', null, null, null, 'none', null, null, null, null);
  perform public.create_reservation(p, 'demo-4', g[4], bd + 1, bd + 4, ste, bar, 2, 1, 'confirmed', 'direct', null, null, null, 'none', null, null, null, null);
  perform pg_temp.act('rsv');
  r := public.create_reservation(p, 'demo-5', g[5], bd + 7, bd + 10, dlx, corp, 1, 0, 'confirmed', 'corporate', 'Dangote Group', null, null, 'deposit', null, null, null, null);
  perform public.post_payment(public.open_main_folio(r), (select id from public.payment_methods where property_id = p and code = 'TRANSFER'), 112500, 'NGN', true, 'Deposit', 'TRF-2201', 'demo-d1');
  perform public.create_reservation(p, 'demo-6', g[6], bd + 2, bd + 3, std, bar, 1, 0, 'tentative', 'phone', null, null, null, 'none', now() + interval '20 hours', null, null, null);

  -- Housekeeping and maintenance
  perform pg_temp.act('hks');
  v := public.create_hk_task((select id from public.rooms where property_id = p and room_number = '102'), 'deep_clean', 'normal', (select id from demo_ids where role = 'att'), 'Carpet');
  perform public.save_lost_found_item(p, 'Black phone charger', 'Room 105', now(), (select id from public.rooms where property_id = p and room_number = '105'));
  perform pg_temp.act('mnt');
  perform public.create_ticket(p, 'Air conditioner noisy', 'Rattles at night', (select id from public.rooms where property_id = p and room_number = '204'), null, 'high', null);
  execute 'reset role';
end \$\$;
SQL
echo "Demo hotel ready: Lagoon View Ikoyi. Sign-ins are in $env_file (git-ignored)."
